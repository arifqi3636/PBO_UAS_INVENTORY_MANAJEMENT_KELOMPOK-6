    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            String namaBarang, hargaBarang, jumlahBarang;
            int hargaInt, jumlahInt;
            namaBarang = tfnmBarang.getText();
            hargaBarang = tfharga.getText();
            hargaInt = Integer.parseInt(hargaBarang);
            jumlahBarang = tfjumlah.getText();
            jumlahInt = Integer.parseInt(jumlahBarang);

            pst = conn.prepareStatement("INSERT INTO data_barang (nama_barang, harga, jumlah) VALUES (?, ?, ?)");
            pst.setString(1, namaBarang);
            pst.setInt(2, hargaInt);
            pst.setInt(3, jumlahInt);

            int i = pst.executeUpdate();
            if (i > 0) {
                JOptionPane.showMessageDialog(this, "Data telah berhasil ditambahkan :)");
                tampilData(); // Refresh tabel
            } else {
                JOptionPane.showMessageDialog(this, "Data gagal ditambahkan :(");
            }

        } catch (SQLException ex) {
            Logger.getLogger(inventoryApplication.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        tfnmBarang.setText(" ");
        tfjumlah.setText(" ");
        tfharga.setText(" ");

    }//GEN-LAST:event_jButton1ActionPerformed

