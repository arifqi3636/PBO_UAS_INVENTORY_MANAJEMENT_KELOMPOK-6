    public void tampilData() {
        DefaultTableModel dft = new DefaultTableModel();
        dft.addColumn("ID");
        dft.addColumn("Nama Barang");  // Sesuaikan dengan tabel data_barang
        dft.addColumn("Harga");
        dft.addColumn("Jumlah");
        try {
            // Gunakan koneksi yang sudah dibuat di kelas ini
            // Asumsikan conn adalah variabel Connection yang sudah terhubung (dari Connect())
            String sql = "SELECT * FROM data_barang";
            PreparedStatement pst = conn.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();
            while (rs.next()) {
                dft.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("nama_barang"),
                    rs.getInt("harga"),
                    rs.getInt("jumlah")
                });
            }
            jTable1.setModel(dft);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }


